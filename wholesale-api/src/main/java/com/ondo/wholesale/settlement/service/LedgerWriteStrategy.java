package com.ondo.wholesale.settlement.service;

/**
 * 미수 잔액을 동시 쓰기로부터 지키는 방법 (MUL-143).
 *
 * <p><b>왜 셋인가</b> — 어느 쪽이 나은지는 조건에 따라 다르다. 충돌이 드물면 낙관적이
 * 유리하고, 잦으면 재시도가 쌓여 오히려 손해다. 같은 조건에서 재보고 고르려고 셋을 둔다.
 *
 * <p><b>애초에 잔액을 덮어쓰지 않는다.</b> 원장은 추가 전용이고 줄마다 그 시점 잔액을 같이
 * 적는다. 그래서 잃어버린 갱신(Lost Update)은 원장 자체에는 생기지 않는다. 문제는
 * <b>순서</b>다 — 두 요청이 같은 잔액을 읽고 각자 이어 쓰면 두 줄의 {@code balance_after}
 * 가 같은 값에서 출발해 장부가 틀어진다. 여기 잠금은 값을 지키려는 게 아니라
 * <b>순서를 지키려는</b> 것이다.
 */
public enum LedgerWriteStrategy {

    /**
     * 아무것도 안 한다. 깨지는 것을 보여주려고 둔다 — 측정에서만 쓴다.
     *
     * <p>둘이 같은 잔액을 읽고 각자 이어 쓰면 나중 것이 앞 것을 덮는다.
     */
    NONE,

    /**
     * 잠그지 않고 쓰되, 읽은 뒤 누가 바꿨으면 실패시킨다.
     *
     * <p>잔액을 고칠 때 {@code balance_version} 을 조건에 넣는다. 그 사이 다른 요청이
     * 올렸으면 0 행이 바뀌고 {@link LedgerConflictException} 이 난다. 부르는 쪽이
     * 트랜잭션을 되돌리고 다시 한다.
     *
     * <p>기다리지 않는 대신 <b>충돌하면 일을 통째로 다시 한다.</b> 같은 거래처에 쓰기가
     * 몰리면 재시도가 쌓인다.
     */
    OPTIMISTIC,

    /**
     * 거래처 행을 {@code FOR UPDATE} 로 잠가 한 줄로 세운다. 지금 쓰는 방법이다.
     *
     * <p>뒤에 선 요청이 기다리므로 헛일이 없다. 대신 잠금을 쥔 동안 다른 요청이 멈춘다 —
     * 그래서 잠금 안에서는 원장 쓰기 말고 아무것도 하지 않는다.
     */
    PESSIMISTIC
}
