--  거래처 잔액 버전 (MUL-143)
--
--  미수 잔액을 지키는 방법이 하나가 아니다. 지금은 거래처 행을 FOR UPDATE 로 잠가
--  같은 거래처의 정산 쓰기를 한 줄로 세운다. 대안은 낙관적 락 — 잠그지 않고 쓰되
--  읽은 뒤 누가 바꿨으면 실패시키고 다시 한다.
--
--  어느 쪽이 나은지는 조건에 따라 다르다. 충돌이 드물면 낙관적이 유리하고, 잦으면
--  재시도가 쌓여 오히려 손해다. 그래서 둘을 같은 조건에서 재보려고 버전 칸을 둔다.
--
--  비관적 락만 쓸 때는 이 칸이 놀고 있다 — 값이 늘지 않을 뿐 해가 없다.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE wholesale.partner
    ADD COLUMN balance_version bigint NOT NULL DEFAULT 0;

COMMENT ON COLUMN wholesale.partner.balance_version IS
    '미수 잔액 낙관적 락용. 잔액을 고칠 때 같이 올린다. 비관적 락 전략에서는 안 쓴다 (MUL-143)';
