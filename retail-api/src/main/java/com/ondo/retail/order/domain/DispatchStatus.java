package com.ondo.retail.order.domain;

/**
 * 접수 대기함 줄의 상태 (MUL-139).
 *
 * <p>{@link #PENDING} 만 워커가 집는다. 나머지 넷은 끝난 상태다.
 *
 * <p><b>{@link #REJECTED} 와 {@link #EXPIRED} 를 나눈 이유</b> — 도매가 "재고가 없다" 고
 * 한 것과 "도매가 안 떠서 못 보냈다" 는 완전히 다르다. 앞은 백 번 해도 실패하니 즉시
 * 끝내야 하고, 뒤는 다시 해보면 된다. 섞어 두면 안 될 일을 계속 두드리게 된다.
 */
public enum DispatchStatus {

    /** 보낼 차례를 기다린다. 워커가 집는 유일한 상태다. */
    PENDING,

    /** 도매가 받았다. 409(이미 있음)도 여기다 — 주문은 도매 장부에 있다. */
    SENT,

    /** 도매가 거절했다. 재고 부족·판매 종료·가격 변동. <b>재시도하지 않는다.</b> */
    REJECTED,

    /**
     * 기한을 넘겼거나 시도 횟수를 다 썼다. 죽은편지함이다.
     *
     * <p>표를 따로 두지 않는다 — 이미 이 표에 줄이 있는데 같은 데이터를 두 곳에 둘 이유가 없다.
     * <b>자동 재처리도 하지 않는다.</b> 기한이 지나서 떨어진 것을 되살리면 기한을 둔
     * 이유를 스스로 부정하는 셈이다.
     */
    EXPIRED,

    /** 소매처가 기다리지 않기로 했다. 다른 도매에서 사기로 한 경우다. */
    CANCELLED;

    public boolean isFinished() {
        return this != PENDING;
    }
}
